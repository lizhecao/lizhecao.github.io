import assert from 'node:assert/strict';
import {visibleParts, furnitureObjects, hitObject, ViewMemory, dimensions} from '../source/block-play/scene-state.mjs';
const part=(zone,extra={})=>({x:1,z:1,y:zone==='second'?4.5:0,w:1,d:1,c:'blue',zone,...extra});
const model={id:'test',steps:[part('base'),part('first',{shell:true}),part('first',{objectId:'bed-a',role:'bed'}),part('second',{kind:'plate',role:'floor'}),part('second',{objectId:'bed-b',role:'bed'}),part('second',{objectId:'bed-c',role:'bed'}),part('roof')].map(p=>({pieces:[p]})),objects:{'bed-b':{name:'床 B'},'bed-c':{name:'床 C'}}};
assert.equal(visibleParts(model,{current:2,preview:false,section:'second'}).length,0);
const view={current:2,preview:true,section:'second',openWalls:true};
assert.deepEqual(visibleParts(model,view).map(p=>p.index),[3,4,5]);
assert.equal(visibleParts(model,{...view,section:'first'}).some(p=>p.shell),false);
assert.equal(visibleParts(model,{...view,section:'first',openWalls:false}).some(p=>p.shell),true);
assert.equal(furnitureObjects(model,visibleParts(model,view)).length,2);
assert.equal(hitObject(visibleParts(model,view),4),'bed-b');
assert.equal(hitObject(visibleParts(model,view),2),null);
assert.equal(hitObject(visibleParts(model,{...view,preview:false}),4),null,'Never pick future parts');
const mirrored=visibleParts(model,{...view,mirror:true});
assert.equal(mirrored[1].objectId,'bed-b');
assert.equal(mirrored[1].x,10);
assert.equal(hitObject(mirrored,5),'bed-c','Stable indices after rebatching/mirror');
const memory=new ViewMemory();
memory.save('test',false,{section:'first',camera:{position:[1,2,3],target:[0,0,0],zoom:2}});
memory.save('test',true,{section:'second',camera:{position:[3,2,1],target:[0,4,0],zoom:1}});
assert.equal(memory.restore('test',false).section,'first');
const saved=memory.restore('test',false);saved.camera.position[0]=9;
assert.equal(memory.restore('test',false).camera.position[0],1,'Snapshot cannot mutate saved state');
assert.equal(dimensions(part('first')).height,.6);
assert.equal(dimensions(part('first',{kind:'plate'})).height,.3);
assert.equal(dimensions(part('base',{kind:'baseplate'})).top,0);
console.log('PASS: built/preview visibility, floor walls, distinct furniture, stable picking, mirror, independent camera snapshots and Duplo proportion');
